def cloudflare_acme_enabled() -> bool:
    return bool(os.environ.get("CLOUDFLARE_API_TOKEN", "").strip())


def write_caddyfile() -> None:
    settings = get_settings()
    hostname = settings["public_url"]
    email = settings["acme_email"]
    token = cloudflare_acme_enabled()
    global_block = f"""# Generated by Mail Exchange — do not edit manually
{{
\temail {email}
}}
"""
    if token:
        # Con token: HTTP su :80 per IP/fallback; HTTPS con LE DNS-01 solo sul FQDN.
        content = (
            global_block
            + """
:80 {
\treverse_proxy mx-frontend:80
}

"""
            + f"""https://{hostname} {{
\ttls {{
\t\tdns cloudflare {{$CLOUDFLARE_API_TOKEN}}
\t\tresolvers 1.1.1.1 1.0.0.1 8.8.8.8
\t}}
\treverse_proxy mx-frontend:80
}}
"""
        )
    else:
        # Senza token: HTTP su :80 per qualsiasi Host (IP o FQDN); HTTPS solo su :443 con cert interno.
        content = (
            global_block
            + """
:80 {
\treverse_proxy mx-frontend:80
}

"""
            + f"""https://{hostname} {{
\ttls internal
\treverse_proxy mx-frontend:80
}}
"""
        )
    (GENERATED_DIR / "Caddyfile").write_text(content, encoding="utf-8")

OPENDKIM_DIR = GENERATED_DIR / "opendkim"
